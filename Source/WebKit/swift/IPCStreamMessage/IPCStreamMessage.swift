// The decoder of an IPC stream message, read from the bytes that the sending process wrote into the stream connection's
// shared memory: the header (IPCStreamHeader.swift), and then, for a message whose arguments have a layout
// (IPC::swiftArgumentLayout(), generated by messages.py; IPCStreamMessageSwiftBoundary.h documents the values), the
// arguments (IPCArgDecoders.swift), in one call from IPC::Decoder::Decoder(std::span<const uint8_t>, uint64_t)
// (Source/WebKit/Platform/IPC/Decoder.cpp). This replaces the body of that constructor, and the
// decoder.decode<Message::Arguments>() that IPC::handleMessage() calls for those messages, whose decodeArgumentsInSwift()
// glue (GPUProcess/graphics/RemoteGraphicsContextSwiftArgumentDecoders.cpp) builds the C++ arguments from what this
// locates.
//
// Locating the arguments with the header doesn't change what is decoded: nothing decodes from a stream message's decoder
// between its construction and IPC::handleMessage(), which decodes the arguments right where the header ends (the glue
// requires it: Decoder::isAtArguments(), checked in debug builds). Each validated value (message name, reply ID, enums,
// identifiers) is read once and returned by value; the values that accept every bit pattern stay in the span for the
// glue to copy.

/// Decodes the header of the stream message in `stream`, then, if it succeeded and `layouts` has a layout other than
/// None for the message name, locates the arguments. Stores all of `arguments` (the bytes of
/// WebKitSwift_IPCStreamMessage_Arguments), status None if it located nothing. A message name is valid iff it indexes
/// `layouts` (which has MessageName::Last + 1 entries). `baseMisalignment` and `firstMessageNameWithReplyID` are as for
/// decodeIPCStreamHeader().
@inline(__always)
func decodeIPCStreamMessage(_ stream: RawSpan, baseMisalignment: Int, destinationID: UInt64, firstMessageNameWithReplyID: UInt16,
                            layouts: Span<UInt8>, arguments: inout MutableRawSpan) -> IPCStreamHeader {
    let header = decodeIPCStreamHeader(stream, baseMisalignment: baseMisalignment, destinationID: destinationID,
                                       messageNameCount: layouts.count, firstMessageNameWithReplyID: firstMessageNameWithReplyID)
    var located = IPCStreamArguments()
    if header.status == .success {
        let layout = layouts[Int(header.messageName)]
        if layout != 0 {
            var reader = IPCArgumentDecoders.Reader(stream, baseMisalignment: baseMisalignment, position: header.argumentsOffset)
            located = IPCArgumentDecoders.locateArguments(&reader, layout: layout)
        }
    }
    located.store(into: &arguments)
    return header
}

/// decode<Message::Arguments>() for the arguments of `layout` from `position` of `stream`, for a decoder that isn't a
/// stream message's (an out-of-stream message): stores all of `arguments`, as decodeIPCStreamMessage() does.
@inline(__always)
func locateIPCArguments(_ stream: RawSpan, baseMisalignment: Int, position: Int, layout: UInt8, arguments: inout MutableRawSpan) {
    // A decoder's position is never past the end of its span.
    precondition(position >= 0 && position <= stream.byteCount, "IPC decoder position outside its span")
    var reader = IPCArgumentDecoders.Reader(stream, baseMisalignment: baseMisalignment, position: position)
    IPCArgumentDecoders.locateArguments(&reader, layout: layout).store(into: &arguments)
}
